const { test } = require('node:test');
const assert = require('node:assert/strict');
const { editor, relativeRepositoryPath, workspaceContext, captureEditorContext, backendLineRange, GitContext } = require('../.test-output/activation.cjs');
const uri = value => editor.Uri.parse(value);
const folder = value => ({ uri: uri(value), name: value.split('/').at(-1), index: 0 });
const sha = 'a'.repeat(40);

test('workspace detection handles no folder, multi-root, outside, untitled and remote metadata safely', () => {
  editor.workspace.workspaceFolders = undefined; editor.window.activeTextEditor = undefined;
  assert.equal(workspaceContext().folders.length, 0);
  const first = folder('file:///C:/Work/one'); const second = folder('file:///C:/Work/two');
  editor.workspace.workspaceFolders = [first];
  assert.equal(workspaceContext().multiRoot, false);
  editor.workspace.workspaceFolders = [first, second];
  editor.window.activeTextEditor = { document: { uri: uri('file:///C:/Work/two/src/main.ts') } };
  assert.equal(workspaceContext().activeFolder, second);
  assert.equal(workspaceContext().multiRoot, true);
  editor.window.activeTextEditor.document.uri = uri('file:///C:/elsewhere/a.ts');
  assert.equal(workspaceContext().activeFolder, undefined);
  editor.window.activeTextEditor.document.uri = uri('untitled:Untitled-1');
  assert.equal(workspaceContext().activeFolder, undefined);
  assert.equal(relativeRepositoryPath(uri('file:///C:/Work/repo'), uri('file:///c:/work/REPO/src/a.ts')), 'src/a.ts');
  for (const file of ['file:///C:/Work/repository/a.ts', 'file:///C:/other/a.ts', 'git:///C:/Work/repo/a.ts', 'file:///C:/Work/repo/../a.ts']) assert.equal(relativeRepositoryPath(uri('file:///C:/Work/repo'), uri(file)), undefined);
  assert.equal(relativeRepositoryPath(uri('vscode-remote://ssh-one/home/repo'), uri('vscode-remote://ssh-two/home/repo/a.ts')), undefined);
  assert.equal(relativeRepositoryPath(uri('vscode-remote://ssh-one/home/repo'), uri('vscode-remote://ssh-one/home/repo/a.ts')), 'a.ts');
  editor.workspace.workspaceFolders = undefined; editor.window.activeTextEditor = undefined;
});
test('Git adapter reads official API metadata and follows branch changes and disablement without exposing remotes', async () => {
  const changed = new editor.EventEmitter(); const enabled = new editor.EventEmitter(); const opened = new editor.EventEmitter(); const closed = new editor.EventEmitter();
  const repo = { rootUri: uri('file:///C:/repo'), state: { HEAD: { name: 'main', commit: sha }, remotes: [{ name: 'origin', fetchUrl: 'https://token:secret@github.com/Owner/Repo.git' }], indexChanges: [], mergeChanges: [], workingTreeChanges: [{}], onDidChange: changed.event } };
  const api = { repositories: [repo], onDidOpenRepository: opened.event, onDidCloseRepository: closed.event };
  const exports = { enabled: true, onDidChangeEnablement: enabled.event, getAPI: version => { assert.equal(version, 1); return api; } };
  editor.extensions.getExtension = () => ({ activate: async () => exports });
  editor.workspace.isTrusted = true;
  const adapter = new GitContext(); await adapter.initialize();
  assert.equal(adapter.read(uri('file:///c:/REPO')).identity, 'https://github.com/owner/repo');
  assert.deepEqual(adapter.read(uri('file:///C:/repo/src/a.ts')), { rootUri: 'file:///C:/repo', identity: 'https://github.com/owner/repo', branch: 'main', head: sha, dirty: true });
  let changes = 0; adapter.onDidChange(() => changes++);
  repo.state.HEAD = { name: 'feature', commit: 'b'.repeat(40) }; changed.fire();
  assert.equal(adapter.read(uri('file:///C:/repo')).branch, 'feature'); assert.equal(changes, 1);
  exports.enabled = false; enabled.fire(false);
  assert.deepEqual(adapter.read(uri('file:///C:/repo')), {});
  adapter.dispose(); assert.equal(changed.listeners.size, 0); assert.equal(enabled.listeners.size, 0);
  editor.extensions.getExtension = () => undefined;
  const unavailable = new GitContext(); await unavailable.initialize(); assert.deepEqual(unavailable.read(uri('file:///C:/repo')), {}); unavailable.dispose();
});
test('editor context keeps exact 0-based positions, uses repository root and never reads document contents', () => {
  const workspace = folder('file:///C:/repo/packages/app');
  editor.workspace.isTrusted = true; editor.workspace.workspaceFolders = [workspace];
  const binding = { snapshotId: 'snap-1', repositoryIdentity: 'https://github.com/a/b', indexedCommit: sha };
  const git = { read: () => ({ rootUri: 'file:///C:/repo', identity: 'https://github.com/a/b', head: sha }) };
  editor.window.activeTextEditor = { document: { uri: uri('file:///C:/repo/packages/app/src/a.ts'), isDirty: true, getText: () => { throw new Error('Must not read source'); } }, selection: { start: { line: 4, character: 2 }, end: { line: 8, character: 0 }, isEmpty: false } };
  const context = captureEditorContext(git, () => binding);
  assert.equal(context.file, 'packages/app/src/a.ts'); assert.equal(context.hasUnsavedChanges, true); assert.equal(context.revision, 'matched');
  assert.deepEqual(context.selection, { start: { line: 4, character: 2 }, end: { line: 8, character: 0 } });
  assert.deepEqual(backendLineRange(context.selection), { startLine: 5, endLine: 8 });
  assert.deepEqual(backendLineRange({ start: { line: 4, character: 0 }, end: { line: 4, character: 0 } }), { startLine: 5, endLine: 5 });
  editor.workspace.isTrusted = false; assert.equal(captureEditorContext(git, () => binding), undefined);
  editor.workspace.isTrusted = true; editor.workspace.workspaceFolders = undefined; editor.window.activeTextEditor = undefined;
});
