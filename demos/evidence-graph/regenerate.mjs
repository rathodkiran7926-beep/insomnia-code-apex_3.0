// Run from any directory: node demos/evidence-graph/regenerate.mjs
// This analyses the teaching fixture only. It executes none of its source code.
import { writeFileSync } from "node:fs";
import { analyze } from "../../backend/src/analyzer.js";

const files = {
  "app.ts": `import express from 'express';
import { signupHandler } from './handlers';

const app = express();
app.post('/signup', signupHandler);
`,
  "handlers.ts": `import { createUser } from './users';

export function signupHandler(req, res) {
  const user = createUser(req.body.email);
  return res.json(user);
}
`,
  "users.ts": `export function createUser(email) {
  const user = { email, verified: false };
  return user;
}
`,
};
const graph = analyze({
  repository: "https://github.com/example/teaching-fixture",
  commit: "d".repeat(40),
  files,
});
writeFileSync(
  new URL("./graph-data.js", import.meta.url),
  "// Generated by the real repository analyzer from an illustrative fixture.\n" +
    "window.EVIDENCE_DEMO = " +
    JSON.stringify({ files, graph }, null, 2) +
    ";\n",
);
console.log(
  `Teaching fixture: ${graph.components.length} components, ${graph.relationships.length} relationships. No source was executed.`,
);
